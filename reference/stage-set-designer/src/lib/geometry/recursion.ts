import { inset } from './clipper'
import { area, centroid } from './polygon'
import { hash32, mulberry32 } from './random'
import { PATTERN_GENERATORS } from './patterns'
import { applyRadialModulation } from './radialModulation'
import { applyDispersion } from './dispersion'
import { MIN_BOUNDARY_AREA } from './constants'
import type { PatternConfig, Point, Polygon } from './types'
import type { PatternContext } from './patterns/types'

export interface CellNode {
  polygon: Polygon // the INSET (cut-ready) polygon
  level: number
  area: number
  children: CellNode[]
}

export interface PatternRunState {
  remaining: number
  truncated: boolean
  totalCells: number
  maxLevelReached: number
  sliversTrimmed: number
}

export function createRunState(maxLeafCells: number): PatternRunState {
  return { remaining: maxLeafCells, truncated: false, totalCells: 0, maxLevelReached: 0, sliversTrimmed: 0 }
}

/**
 * Builds a tree of cells by recursively subdividing `boundary`. Each level's
 * raw cells are generated by the pattern-specific generator, sliver-trimmed,
 * then inset by (strut+kerf)/2 — one Clipper call per cell, since cells
 * share edges and batch-offsetting them would inset their union instead.
 */
export function buildPatternTree(
  boundary: Polygon,
  config: PatternConfig,
  state: PatternRunState,
  level: number,
  cellIndex: number,
  cellSize: number,
  strut: number,
  patternCenter: Point,
  patternMaxRadius: number,
): CellNode[] {
  if (state.remaining <= 0) {
    state.truncated = true
    return []
  }
  if (area(boundary) < MIN_BOUNDARY_AREA) return []

  state.maxLevelReached = Math.max(state.maxLevelReached, level)

  // Level 0 anchors the lattice at the TRUE pattern center, not the local
  // boundary's own centroid. For a symmetry wedge (a pie slice) those
  // differ a lot — a pie slice's centroid sits well away from its apex —
  // and anchoring there misaligns the lattice near the middle, clipping
  // cells at the apex into small, inconsistent slivers independent of
  // anything the radial-modulation size gradient asks for. Anchored at the
  // true center instead, the lattice has a cell CENTERED on the apex, so
  // each wedge holds an exact 1/N pie-slice of it — and the N rotated
  // copies reassemble into one correctly-sized cell at the very middle.
  // Deeper recursion levels keep using their own parent cell's centroid,
  // which is a different (and already-correct) concern: aligning a child
  // sub-pattern within its own parent, not the overall symmetry wedge.
  const origin = level === 0 ? patternCenter : centroid(boundary)
  const rng = mulberry32(hash32(config.seed, level, cellIndex))
  const generator = PATTERN_GENERATORS[config.kind]
  const ctx: PatternContext = { boundary, origin, cellSize, level, rng, config, patternCenter, patternMaxRadius }

  let rawCells = generator(ctx)

  if (config.trimSlivers) {
    const nominal = cellSize * cellSize
    const threshold = nominal * config.sliverAreaRatio
    const before = rawCells.length
    rawCells = rawCells.filter((c) => area(c) >= threshold)
    state.sliversTrimmed += before - rawCells.length
  }

  // Applied after sliver-trimming (which must judge raw lattice geometry,
  // not intentionally-shrunk edge cells) and before strut-inset.
  if (config.radialModulation.enabled) {
    rawCells = applyRadialModulation(rawCells, patternCenter, patternMaxRadius, config.radialModulation)
  }
  if (config.dispersion.enabled) {
    rawCells = applyDispersion(rawCells, cellSize, config.dispersion, rng)
  }

  const effectiveInset = (strut + config.kerf) / 2
  const nodes: CellNode[] = []

  for (let i = 0; i < rawCells.length; i++) {
    if (state.remaining <= 0) {
      state.truncated = true
      break
    }
    const insetResults = inset(rawCells[i], effectiveInset, config.cornerStyle)
    for (const insetPoly of insetResults) {
      if (insetPoly.length < 3) continue
      const a = area(insetPoly)
      if (a <= 0) continue
      if (state.remaining <= 0) {
        state.truncated = true
        break
      }

      state.remaining--
      state.totalCells++
      const node: CellNode = { polygon: insetPoly, level, area: a, children: [] }

      const canRecurse =
        level < config.recursion.depth && a >= config.recursion.minCellArea && state.remaining > 0

      if (canRecurse) {
        const childCellSize = cellSize * config.recursion.childScale
        const childStrut = Math.max(config.minStrutWidth, strut * config.recursion.strutFalloff)
        node.children = buildPatternTree(
          insetPoly,
          config,
          state,
          level + 1,
          i,
          childCellSize,
          childStrut,
          patternCenter,
          patternMaxRadius,
        )
      }

      nodes.push(node)
    }
  }

  return nodes
}

export function collectLeaves(nodes: CellNode[]): Polygon[] {
  const result: Polygon[] = []
  for (const n of nodes) {
    if (n.children.length === 0) result.push(n.polygon)
    else result.push(...collectLeaves(n.children))
  }
  return result
}

export function collectAll(nodes: CellNode[]): Polygon[] {
  const result: Polygon[] = []
  for (const n of nodes) {
    result.push(n.polygon)
    result.push(...collectAll(n.children))
  }
  return result
}
